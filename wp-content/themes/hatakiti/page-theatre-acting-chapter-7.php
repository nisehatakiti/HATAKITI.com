<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>重心を変えるだけでも、その人がどんな状態なのか見え方が変わるんだね。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>実践エチュード</h2>
<p>重心の変化を組み合わせて、身体から人物をつくってみます。</p>
</div>
<div class="hk-exercise">
<h3>重心を変えて人物をつくる　10分</h3>
<ol>
<li>普通に立つ。</li>
<li>重心を少し前へ移す。</li>
<li>重心を少し後ろへ移す。</li>
<li>右・左へ重心を移す。</li>
<li>重心を少し高く・低くする。</li>
<li>安定した状態と少し不安定な状態を比べる。</li>
<li>人物の目的を一つ設定する。</li>
<li>目的を持った状態で立つ、歩く、短い台詞を言う。</li>
<li>見る側は「どう見えたか」を伝える。</li>
<li>演じた側は「何を意図したか」を伝える。</li>
</ol>
<p><strong>ポイント：</strong>大きく身体を傾けることが目的ではありません。小さな重心の変化から、身体の状態や人物の目的がどう見えるのかを感じてみましょう。</p>
</div>
