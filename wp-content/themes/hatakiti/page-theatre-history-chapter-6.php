    <section class="hk-section">
        <div class="hk-section-head"><h2>6-3　ブレヒトと「考える観客」</h2></div>
        <p>ドイツの劇作家・演出家ベルトルト・ブレヒトは、観客を物語に完全に入り込ませるだけではなく、舞台を少し離れたところから見て、社会について考える演劇を提案しました。</p>
        <p>たとえば俳優が観客に直接語りかけたり、舞台の仕組みを見せたり、場面の途中で歌や説明を入れたりすることで、観客に「これは演劇を見ている」という意識を持たせます。</p>
        <p>目的は、感動をなくすことではありません。<strong>舞台を見ながら、なぜこうなっているのか、社会ではどうなのかと考える余地を作る</strong>ことにあります。</p>
        <figure class="hk-history-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/history/history-chapter6-02-brecht-and-thinking-audience.png' ) ); ?>" alt="ブレヒトの演劇と考える観客の関係を説明する図" loading="lazy"></figure>
