    <section class="hk-section">
        <div class="hk-section-head"><h2>6-8　観客も「参加する」</h2></div>
        <p>さらに現代演劇では、観客を「見るだけの人」として考えない作品も生まれます。</p>
        <p>観客が舞台の中を移動したり、いくつかの選択肢から行動を選んだり、俳優と直接関わったりする作品です。</p>
        <p>観客が参加することで、同じ作品でも参加した人や、その場の状況によって体験が変わります。ここでは、<strong>観客も上演を成立させる存在</strong>だという考え方が、よりはっきりしてきます。</p>
    </section>

    <section class="hk-section">
        <div class="hk-section-head"><h2>6-9　日本の現代演劇</h2></div>
        <p>日本でも、近代の新劇を出発点として、戦後にさまざまな演劇の動きが生まれました。大きな劇場を中心とする演劇だけでなく、小さな劇場や街の空間を使い、既存の演劇の形に問いを投げかける活動も広がります。</p>
        <p>1960年代以降には、アングラ演劇や小劇場運動が活発になり、演劇と社会、身体、都市、観客との関係を問い直す作品が登場しました。</p>
        <p><strong>寺山修司</strong>は演劇実験室「天井棧敷」を主宰し、演劇だけでなく詩、映画など複数の表現を横断しながら活動しました。天井棧敷の公演には、既存の劇場の枠を越える発想や強い視覚性を持つ作品もあり、日本の前衛的な演劇を考えるうえで重要な存在です。</p>
        <p>一方、<strong>浅利慶太</strong>は1953年に劇団四季を創設し、ストレートプレイからミュージカルまで幅広い作品を手がけました。劇団四季は継続的な公演と劇場運営を発展させ、後の日本のミュージカル文化にも大きな位置を占めるようになります。</p>
        <p>寺山修司と浅利慶太は、活動の方向性も作品づくりの方法も大きく異なります。しかし、二人を並べて見ると、戦後日本の演劇が<strong>一つの方向だけではなく、実験性と継続的な興行の両方を含めて多様化していった</strong>ことが分かります。</p>
