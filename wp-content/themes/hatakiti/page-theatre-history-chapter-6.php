    <section class="hk-section">
        <div class="hk-section-head"><h2>6-2　俳優の身体をもっと自由にする</h2></div>
        <p>演技を考えるとき、台詞だけに注目する必要はありません。身体の形、動き、リズム、呼吸、声、ダンスなども、舞台上で意味を持ちます。</p>
        <p>20世紀には、俳優の身体そのものを表現の中心に置く考え方が広がりました。人物を日常生活と同じように動かすのではなく、身体を大きく変形させたり、集団で動いたり、ダンスと演劇を組み合わせたりする方法です。</p>
        <div class="hk-nyakakichi">
            <div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-interested.png' ) ); ?>" alt="身体表現に興味を持つにゃかきち" loading="lazy"></div>
