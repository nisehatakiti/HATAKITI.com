    <section class="hk-section">
        <div class="hk-section-head"><h2>6-7　劇場の外へ出る</h2></div>
        <p>演劇を行う場所も変化します。劇場の舞台だけではなく、街、公園、倉庫、廃墟、美術館、学校など、さまざまな場所が上演空間になります。</p>
        <p>場所が変われば、観客との距離も、俳優の動きも、音の聞こえ方も変わります。つまり「どこで演じるか」そのものが、作品の一部になるのです。</p>
