    <section class="hk-section">
        <div class="hk-section-head"><h2>6-10　演劇は一つの形ではなくなった</h2></div>
        <p>20世紀の演劇を見ていくと、リアリズムだけでなく、身体表現、社会について考える演劇、不条理、実験演劇、野外演劇、観客参加型の演劇など、さまざまな方向が生まれていることが分かります。</p>
        <p>つまり現代演劇では、「演劇とはこういうもの」という一つの形に決めることが難しくなりました。</p>
        <p>物語を見せてもいい。身体だけで表現してもいい。観客に考えてもらってもいい。劇場の外へ出てもいい。観客に参加してもらってもいい。</p>
        <p>大切なのは、何を表現したいのか、そのために<strong>どんな方法、どんな空間、どんな俳優と観客の関係を選ぶのか</strong>ということです。</p>
        <figure class="hk-history-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/history/history-chapter6-05-many-forms-of-theatre.png' ) ); ?>" alt="現代演劇がリアリズム、身体表現、社会、不条理、実験、野外、観客参加などへ多様化したことを示す図" loading="lazy"></figure>
