    <section class="hk-section">
        <div class="hk-section-head"><h2>6-4　演劇は「物語」だけではない</h2></div>
        <p>演劇といえば、台本に物語があり、それを俳優が演じるものだと考えがちです。しかし20世紀には、物語そのものを中心に置かない舞台表現も増えていきます。</p>
        <p>言葉を減らし、身体、音、光、映像、舞台空間などを組み合わせる。あるいは、ほとんど何もない空間に俳優だけを置く。</p>
        <p>こうした実験によって、演劇は「物語を伝える方法」から、<strong>その場で何かを体験させる表現</strong>へも広がっていきました。</p>
    </section>

    <section class="hk-section">
        <div class="hk-section-head"><h2>6-5　アルトーと「身体の演劇」</h2></div>
        <p>フランスのアントナン・アルトーは、言葉中心の演劇に疑問を投げかけ、身体、音、光、空間などを強く使う演劇を考えました。</p>
        <p>アルトーが「残酷」と呼んだ演劇は、単に暴力的な作品を作るという意味ではありません。観客の感覚を揺さぶり、普段とは違う強い体験を生み出す演劇を考えたのです。</p>
        <p>この考え方は、後の身体表現や実験的な演劇を考えるうえでも重要な出発点の一つになりました。</p>
    </section>

    <section class="hk-section">
        <div class="hk-section-head"><h2>6-6　「不条理演劇」が生まれる</h2></div>
        <p>第二次世界大戦後には、明確な目的や結末を持つ物語だけでは、人間の不安や世界の不確かさを表現しにくいと考える演劇も登場します。</p>
        <p>サミュエル・ベケットやウジェーヌ・イヨネスコの作品では、会話がかみ合わなかったり、同じ行動が繰り返されたり、物語がはっきり解決しなかったりします。</p>
        <p>これは、観客に答えを与えるためだけの演劇ではありません。<strong>解決しない状況そのものを見せることで、観客が意味を考える余地を作る</strong>こともできます。</p>
        <figure class="hk-history-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/history/history-chapter6-03-theatre-of-the-absurd.png' ) ); ?>" alt="通常の物語構造と不条理演劇の特徴を比較する図" loading="lazy"></figure>
