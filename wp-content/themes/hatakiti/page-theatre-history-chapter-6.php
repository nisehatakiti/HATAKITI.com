    <section class="hk-section">
        <div class="hk-section-head"><h2>6-1　「現実そっくり」ではない舞台へ</h2></div>
        <p>近代演劇では、現実の生活を舞台に再現することが大きなテーマになりました。しかし20世紀になると、現実をそのまま写すのではなく、夢、感情、記憶、象徴、人間の内面などを舞台で表そうとする動きも生まれます。</p>
        <p>舞台の形や色を大胆に変えたり、現実には存在しない空間を作ったりすることで、観客に別の世界を感じてもらう方法です。</p>
        <p>ここでは、演劇を<strong>現実のコピーではなく、世界を解釈して見せる表現</strong>として考えることが重要になります。</p>
        <figure class="hk-history-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/history/history-chapter6-01-beyond-realism.png' ) ); ?>" alt="現実を再現する舞台から象徴や心の世界を表現する舞台への変化を説明する図" loading="lazy"></figure>
