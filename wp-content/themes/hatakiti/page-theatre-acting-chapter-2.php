<section class="hk-section">
<div class="hk-section-head"><h2>2-1　発声のしくみ</h2><p>声は、息・声帯・共鳴・口の動きがつながって生まれます。</p></div>
<p>声を出そうとすると、つい喉だけに意識が向きます。しかし、声のもとは肺から出る息です。その息が声帯を振動させ、そこで生まれた音が身体の空間で響き、最後に口や舌の動きによって言葉になります。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-voice-01-how-voice-is-produced.png' ) ); ?>" alt="発声のしくみを息、声帯、共鳴、ことばの4段階で示した図説" loading="lazy">
<figcaption>発声は、息から始まり、声帯の振動、共鳴、口の動きを経て言葉になります。</figcaption>
</figure>
<div class="hk-panel"><p><strong>発声は喉だけの仕事ではありません。</strong></p><p>呼吸で息を送り、身体を無理なく使い、響きをつくり、口と舌で音を明確にする。このつながりができると、大声を出さなくても相手に届きやすい声になります。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>2-2　上半身をゆるめて声を響かせる</h2><p>身体を固めて声を出すのではなく、ゆるんだ身体から声が生まれ、その声と一緒に身体が起きてくる感覚を探します。</p></div>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-voice-01-relax-and-resonate.png' ) ); ?>" alt="立った状態で上半身をゆるめ、声を響かせながらゆっくり起き上がる発声エチュード" loading="lazy">
<figcaption>上半身をゆるめ、声を響かせながら、ゆっくり立った姿勢へ戻っていきます。</figcaption>
</figure>
<div class="hk-exercise"><h3>実践エチュード「声で身体を起こす」</h3><ol><li>自然に立ち、膝を固めず、肩・首・胸・お腹の余分な力を抜く。</li><li>上半身の重さを前に預け、頭や腕もぶら下がるようにする。</li><li>その姿勢で小さく「あー」と声を出し、身体のどこに響くか感じる。</li><li>声を途切れさせず、首、胸、上半身の順にゆっくり起き上がる。</li><li>立った姿勢で声を終え、喉で押さずに身体全体が響いている感覚を確認する。</li></ol><p><strong>ポイント：</strong>大きな声を出す練習ではありません。力を入れて声を作るのではなく、ゆるんだ身体から声が生まれる感覚を探します。</p></div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>大きな声を出せば、よく届く声になるのかニャ？</p></div>
</div>
<div class="hk-nyakakichi-followup"><p>大きさよりも、息・身体・響きを使って、無理なく相手へ届く声をつくることが大切です。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>2-3　母音をはっきり発声する</h2><p>まずは「あ・え・い・う・え・お・あ・お」を一音ずつ区切って発声します。</p></div>
<p>母音は、声の響きと口の形を確認する基本練習です。一気に流して読むのではなく、最初は<strong>あ｜え｜い｜う｜え｜お｜あ｜お</strong>と一音ずつ区切ります。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-voice-02-vowel-vocalization.png' ) ); ?>" alt="あえいうえおあおの母音発声を口の形とともに示した図説" loading="lazy">
<figcaption>一音ずつ、口の形・舌の位置・息の流れ・響きを意識して発声します。</figcaption>
</figure>
<div class="hk-panel"><p><strong>口の形を変えることも発声練習です。</strong></p><p>「あ」なら口を大きく開く、「え」なら横に開く、「い」なら口角を引く、「う」なら唇を丸める。このように音によって口や舌の形が変わります。形を丁寧に変えることで、母音の違いが明確になります。</p></div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>母音を練習したら、50音はどう練習するのかニャ？</p></div>
</div>
<div class="hk-nyakakichi-followup"><p>母音の練習と同じ型を各行に当てはめて練習してから、通常の50音へ進みます。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>2-4　各行を同じ型で練習する</h2><p>母音の「あ・え・い・う・え・お・あ・お」という型を、各行に当てはめます。</p></div>
<p>例えば「か行」なら、</p>
<p class="hk-voice-sequence"><strong>か・け・き・く・け・こ・か・こ</strong></p>
<p>「さ行」なら、</p>
<p class="hk-voice-sequence"><strong>さ・せ・し・す・せ・そ・さ・そ</strong></p>
<p>というように、一音ずつ区切って発声します。</p>
<div class="hk-panel"><p><strong>練習の順番</strong></p><ol><li>まず「あ・え・い・う・え・お・あ・お」を練習する。</li><li>次に、か行・さ行・た行……と各行を同じ型で練習する。</li><li>慣れてきたら、一音ずつの間隔を少し短くする。</li><li>その後、通常の50音を一音ずつ発声する。</li></ol></div>
</section>



<section class="hk-section">
<div class="hk-section-head"><h2>2-6　劇場という空間に響かせる</h2><p>発声は、目の前の相手だけでなく、劇場という空間全体に声を届ける技術です。</p></div>
<p>演劇では、相手との距離だけを考えて声を出すわけではありません。舞台上の声は、客席まで届き、劇場という空間の中で響いてはじめて「伝わる声」になります。</p>
<p>声を遠くへ届けようとして喉で押し出すのではなく、<strong>息の流れ、身体の響き、声の方向</strong>を使って、空間全体へ声を広げます。</p>
<div class="hk-panel"><p><strong>劇場では「大声」ではなく「響き」を使います。</strong></p><p>小さな部屋で話すときと、広い劇場の舞台で話すときでは、必要な声の使い方が違います。客席の一番後ろまで届くことを意識しながらも、喉を押して音量だけを上げないことが大切です。</p><p>舞台の中央に立って、客席の奥まで声が届き、さらに劇場全体に響いていくような方向を意識してみましょう。</p></div>
<div class="hk-exercise"><h3>実践エチュード「劇場に声を響かせる」</h3><ol><li>自然に立ち、身体の力を抜いて呼吸する。</li><li>まず近くの相手に話しかけるように声を出す。</li><li>次に、客席の中ほどへ声を届けるつもりで声の方向を変える。</li><li>最後に、客席の一番奥まで声が届くように意識する。</li><li>音量を無理に上げるのではなく、息と響きが空間へ広がっていく感覚を探す。</li></ol><p><strong>ポイント：</strong>声を遠くへ飛ばすことと、喉で押して大声を出すことは別です。身体を使って、劇場全体に響く声をつくります。</p></div>
</section>



<section class="hk-section">
<div class="hk-section-head"><h2>実践エチュード　ひとりでできる発声練習</h2><p>毎日少しずつ、無理のない声で繰り返します。</p></div>
<div class="hk-exercise"><h3>① 母音ロングトーン　5分</h3><ol><li>自然に息を吸う。</li><li>「あー」を小さめの声で一定に伸ばす。</li><li>同じように「え・い・お・う」へ進む。</li><li>喉に力を入れず、響きが安定しているか確認する。</li></ol></div>
<div class="hk-exercise"><h3>② 各行の発声　5分</h3><ol><li>あ行を「あ・え・い・う・え・お・あ・お」と発声する。</li><li>か行、さ行、た行……と同じ型で進む。</li><li>慣れたら通常の50音を一音ずつ発声する。</li></ol></div>
<div class="hk-exercise"><h3>③ 文章で発声　5分</h3><ol><li>好きな本や文章を選ぶ。</li><li>最初はゆっくり、母音と子音を明確に読む。</li><li>息を止めず、相手に話しかけるつもりで読む。</li><li>慣れてきたら少しずつ自然な速度へ戻す。</li></ol></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>付録　北原白秋「五十音」――あめんぼの歌</h2></div>
<div class="hk-voice-poem">
<h3>五十音　北原白秋</h3>
<p>水馬（あめんぼ）赤いな。ア、イ、ウ、エ、オ。<br>浮藻（うきも）に小蝦（こえび）もおよいでる。</p>
<p>柿の木、栗の木。カ、キ、ク、ケ、コ。<br>啄木鳥（きつつき）こつこつ、枯れけやき。</p>
<p>大角豆（ささげ）に醋（す）をかけ、サ、シ、ス、セ、ソ。<br>その魚（うを）浅瀬で刺しました。</p>
<p>立ちましょ、喇叭（らっぱ）で、タ、チ、ツ、テ、ト。<br>トテトテタッタと飛び立った。</p>
<p>蛞蝓（なめくじ）のろのろ、ナ、ニ、ヌ、ネ、ノ。<br>納戸（なんど）にぬめって、なにねばる。</p>
<p>鳩ぽっぽ、ほろほろ。ハ、ヒ、フ、ヘ、ホ。<br>日向（ひなた）のお部屋にゃ笛を吹く。</p>
<p>蝸牛（まゐまゐ）、螺旋巻（ねぢまき）、マ、ミ、ム、メ、モ。<br>梅の実落ちても見もしまい。</p>
<p>焼栗、ゆで栗。ヤ、イ、ユ、エ、ヨ。<br>山田に灯のつく宵の家。</p>
<p>雷鳥（らいてう）は寒かろ、ラ、リ、ル、レ、ロ。<br>蓮花（れんげ）が咲いたら、瑠璃（るり）の鳥。</p>
<p>わい、わい、わっしょい。ワ、ヰ、ウ、ヱ、ヲ。<br>植木屋（うゑきや）、井戸換（ゐどが）へ、お祭だ。</p>
</div>
<div class="hk-panel"><p><strong>速く読むことが目的ではありません。</strong></p><p>この練習では、口・舌・息・声を一緒に使いながら、どの速度でも音を崩さずに発声できることを目指します。速くするのは、ゆっくり読んでも明瞭に発声できるようになってからです。</p></div>
<div class="hk-ame-stage-grid">
<div class="hk-ame-stage"><span>STEP 1</span><h3>ゆっくり読む</h3><p>まずは一語ずつ、意味を確認するくらいの速度で読みます。</p><p class="hk-ame-example">あめんぼ　あかいな<br>あいうえお</p><ul><li>口をしっかり動かす</li><li>一音ずつ明瞭にする</li><li>息を止めない</li></ul></div>
<div class="hk-ame-stage"><span>STEP 2</span><h3>一定の速度で読む</h3><p>文章全体を同じテンポで読みます。途中だけ急がないことがポイントです。</p><ul><li>音の大きさをそろえる</li><li>言葉の終わりまで発声する</li><li>呼吸する場所を決める</li></ul></div>
<div class="hk-ame-stage"><span>STEP 3</span><h3>少しずつ速度を上げる</h3><p>明瞭さを保ったまま、少しだけテンポを上げます。</p><ul><li>口が追いつく範囲で上げる</li><li>息が苦しくなったら戻す</li><li>音が崩れたら一段階遅くする</li></ul></div>
<div class="hk-ame-stage"><span>STEP 4</span><h3>速さに挑戦する</h3><p>最後に、自分が無理なく保てる速度まで上げます。</p><ul><li>速さより明瞭さを優先</li><li>声を押し出さない</li><li>最後まで息と声をつなげる</li></ul></div>
</div>

<div class="hk-exercise"><h3>練習の進め方</h3><ol><li>STEP 1を数回繰り返し、音が崩れないことを確認する。</li><li>STEP 2で一定のテンポを作る。</li><li>STEP 3では少しずつ速度を上げる。</li><li>言い間違えたり音が崩れたりしたら、一つ前の速度に戻る。</li><li>最後にSTEP 4で、今の自分が保てる最高速度に挑戦する。</li></ol><p><strong>目標：</strong>「速く言えること」ではなく、<strong>速くなっても明瞭に、自然に、息を止めずに言えること</strong>です。</p></div>
</section>

