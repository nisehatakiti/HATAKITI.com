<section class="hk-section">
<div class="hk-section-head">
<h2>8-1　感情は身体にも現れる</h2>
<p>感情が動くと、呼吸や姿勢、視線、声など、身体にも変化が現れます。</p>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-08-1-emotion-in-body.png' ) ); ?>" alt="図説①" loading="lazy"></figure>
<p>感情は頭の中だけで起きているものではありません。嬉しいとき、緊張したとき、怖いとき、怒ったとき、悲しいとき。身体の状態も少しずつ変化します。</p>
<p>例えば、呼吸が速くなる、肩に力が入る、視線が動く、身体が前へ出る、逆に後ろへ引くなど、人によってさまざまな変化があります。</p>
<p>ここでは、感情を大きく表現することを目指しません。まず、<strong>自分に感情が起きたとき、身体に何が起きるのかを知る</strong>ことから始めます。</p>
<div class="hk-exercise">
<h3>感情と身体の変化を観察する</h3>
<ol>
<li>自然に立つ。</li>
<li>最近あった「嬉しかったこと」を一つ思い出す。</li>
<li>呼吸、姿勢、視線などの変化を感じる。</li>
<li>次に「緊張したこと」を思い出す。</li>
<li>身体のどこが変わったか確認する。</li>
<li>最後に、何も考えず自然な状態へ戻る。</li>
</ol>
</div>
<div class="hk-nyakakichi">
