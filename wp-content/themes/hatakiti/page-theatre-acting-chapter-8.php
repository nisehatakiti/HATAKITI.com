<div class="hk-nyakakichi-question"><p>感情って、顔だけじゃなくて身体全体に出てくるんだね。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>8-2　感情を作るのではなく気づく</h2>
<p>感情を「作る」のではなく、今の身体と呼吸に起きていることを観察します。</p>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-08-2-notice-emotion.png' ) ); ?>" alt="図説②" loading="lazy"></figure>
<p>演技をするとき、「悲しい顔をしよう」「怒った声を出そう」と先に形を作ってしまうことがあります。</p>
<p>もちろん表情や声も演技の一部ですが、そこから始めるのではなく、まず自分の身体を感じてみます。</p>
<p>呼吸が浅くなった、胸が動いた、肩に力が入った、視線が止まった。そうした小さな変化に気づくことで、感情を無理に作らなくても身体の反応を扱えるようになります。</p>
<div class="hk-exercise">
<h3>身体の変化に気づく</h3>
<ol>
<li>自然に呼吸する。</li>
<li>一つの出来事を思い出す。</li>
<li>表情を作ろうとせず、身体の変化を感じる。</li>
<li>呼吸、肩、胸、手、視線などを観察する。</li>
<li>もう一度、何も考えず自然な状態に戻る。</li>
</ol>
</div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>悲しい顔を作る前に、身体に何が起きてるか見てみるんだね。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>8-3　身体のブレーキに気づく</h2>
<p>感情が動いた瞬間に、自分で反応を止めている場所を見つけます。</p>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-08-3-body-brakes.png' ) ); ?>" alt="図説③" loading="lazy"></figure>
<p>人は、感情が動いたときに無意識に反応を止めることがあります。</p>
<p>笑いそうになって口を閉じる。泣きそうになって息を止める。怒りを感じて身体を固める。緊張して声を小さくする。</p>
<p>こうした反応は「悪いこと」ではありません。まず、<strong>自分がどこで反応を止めているのかに気づく</strong>ことが大切です。</p>
<div class="hk-exercise">
<h3>自分のブレーキを探す</h3>
<ol>
<li>少し感情が動く場面を思い出す。</li>
<li>その瞬間に身体のどこが固くなるか感じる。</li>
<li>呼吸が止まっていないか確認する。</li>
<li>声や視線を抑えていないか確認する。</li>
<li>無理に反応を大きくせず、少しだけ力を抜いてみる。</li>
</ol>
</div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>感情が出ないんじゃなくて、自分で止めてることもあるんだね。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>8-4　感情を行動につなげる</h2>
<p>感情を大きくするのではなく、相手に何を求め、何をしようとしているのかにつなげます。</p>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-08-4-emotion-to-action.png' ) ); ?>" alt="図説④" loading="lazy"></figure>
<p>感情を感じるだけでは、まだ演技にはなりません。舞台では、その感情を持った人物が<strong>何をしようとしているのか</strong>が重要になります。</p>
<p>例えば、怒っているから怒鳴るとは限りません。相手に謝ってほしいのか、離れてほしいのか、振り向いてほしいのか。悲しいから泣くとは限りません。そばにいてほしいのか、何も言わずにいてほしいのか。</p>
<p>感情を行動へつなげることで、身体の変化が人物の目的と結びついていきます。</p>
<div class="hk-exercise">
<h3>感情から行動へつなげる</h3>
<ol>
<li>相手との場面を一つ設定する。</li>
<li>自分の人物が何を感じているのか考える。</li>
<li>その人物が相手に何を求めているのか決める。</li>
<li>言葉を使わず、まず身体で相手に働きかける。</li>
<li>次に短い言葉を一つ加える。</li>
<li>感情と目的がどうつながったか確認する。</li>
</ol>
</div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>怒っているだけじゃなくて、相手に何をしてほしいかまで考えるんだね。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>8-5　感情の変化を受け止める</h2>
<p>一つの感情を固定せず、相手や状況によって変化する身体を感じます。</p>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-08-5-emotion-change.png' ) ); ?>" alt="図説⑤" loading="lazy"></figure>
<p>実際の場面では、感情は一つのまま続くとは限りません。怒っていたところへ相手の言葉が返ってきて迷ったり、悲しかったところへ少し安心したりすることがあります。</p>
<p>演技でも、「最初から最後まで悲しい人」のように感情を固定する必要はありません。相手の言葉や行動を受けることで、自分の身体や呼吸が変化していくことを大切にします。</p>
<div class="hk-exercise">
<h3>感情の変化を感じる</h3>
<ol>
<li>二人で向かい合う。</li>
<li>一人が短い言葉を伝える。</li>
<li>もう一人は、その言葉を受けて身体の変化を感じる。</li>
<li>次に相手が少し違う言葉を伝える。</li>
<li>呼吸、視線、姿勢などがどう変わったか観察する。</li>
<li>感情を決め直すのではなく、その変化を受け止める。</li>
</ol>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>8-6　感情から人物をつくる</h2>
<p>感じたこと、身体の変化、行動をつなげて、一人の人物として演じます。</p>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-08-6-character-from-emotion.png' ) ); ?>" alt="図説⑥" loading="lazy"></figure>
<p>ここまで学んできたことを、人物につなげます。</p>
<p>「この人物は悲しい」「この人物は怒っている」と感情だけを決めるのではありません。</p>
<p><strong>何が起きた → どう感じた → 身体がどう変わった → 相手に何をしようとした</strong>という流れから人物を作ってみます。</p>
<p>感情は、人物を飾るためのものではありません。人物が何を求め、何をしようとしているのかを身体から生み出すための材料です。</p>
<div class="hk-exercise">
<h3>感情から人物をつくる</h3>
<ol>
<li>人物が置かれている状況を一つ設定する。</li>
<li>その人物に起きた出来事を一つ決める。</li>
<li>人物がどう感じたのか考える。</li>
<li>呼吸、姿勢、視線など身体の変化を感じる。</li>
<li>相手に何を求めているのか決める。</li>
<li>その目的を持って短い場面を演じる。</li>
<li>見る側は、どんな状態や人物に見えたか伝える。</li>
<li>演じた側は、自分の意図と見え方を比べる。</li>
</ol>
</div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>感情だけじゃなくて、身体と行動までつながると人物になっていくんだね。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>実践エチュード</h2>
<p>感情の変化を身体で感じながら、相手とのやり取りにつなげます。</p>
</div>
<div class="hk-exercise">
<h3>言いたいのに言えない　10分</h3>
<ol>
<li>相手と向かい合う。</li>
<li>相手に伝えたいことを一つ決める。</li>
<li>すぐには言わず、身体の変化を感じる。</li>
<li>呼吸、姿勢、視線、距離などを観察する。</li>
<li>少しだけ言葉にする。</li>
<li>相手の反応を受ける。</li>
<li>自分の感情や身体がどう変わったか感じる。</li>
<li>最後に、伝えたいことを言葉にする。</li>
<li>見る側は「どう見えたか」を伝える。</li>
<li>演じた側は「何を意図したか」を伝える。</li>
</ol>
<p><strong>ポイント：</strong>泣く、怒る、大声を出すなどの結果を作ることが目的ではありません。感情が動いたときに身体に何が起き、それが相手への行動にどうつながるのかを感じてみましょう。</p>
</div>
