<h3>第8章まとめ</h3>
<p><strong>感じる → 気づく → 止めているものに気づく → 行動につなげる → 変化を受け止める → 人物につなげる。</strong></p>
<p>感情の解放は、感情を大きく見せることではありません。自分の身体に起きている変化を感じ、その反応を止めず、相手への行動や人物の目的へつなげていくことです。</p>
