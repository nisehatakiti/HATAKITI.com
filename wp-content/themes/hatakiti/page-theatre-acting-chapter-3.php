<p>たちつてと　ちつてとた　つてとたち　てとたちつ　とたちつて</p>
<p>なにぬねの　にぬねのな　ぬねのなに　ねのなにぬ　のなにぬね</p>
<p>はひふへほ　ひふへほは　ふへほはひ　へほはひふ　ほはひふへ</p>
