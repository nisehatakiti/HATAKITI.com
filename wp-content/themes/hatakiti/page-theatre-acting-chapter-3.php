</div>
<p><strong>ポイント：</strong>「速く言う」ことが目的ではありません。音が曖昧になったら一段階ゆっくりに戻し、口の動きを確かめます。</p>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>付録　外郎売 ― 言葉を身体になじませる</h2>
<p>第3章で学んだ滑舌を、長い口上の中で実際に使ってみましょう。</p>
</div>
<p>「外郎売」は、俳優の発音練習でよく使われる長い口上です。たくさんの言葉が続き、似た音が連続する部分もあります。</p>
<p>しかし、目的は「外郎売を速く言えるようになること」ではありません。一つひとつの音を明確につくり、言葉をつなげ、意味を持って話し、最後には相手や劇場へ届ける。第3章で学んだ滑舌を、実際の言葉の中で使ってみましょう。</p>

<h3>外郎売本文</h3>
<p class="hk-source-note">以下は二代目市川團十郎による1718年の作品をもとにした本文です。底本は『花江都歌舞妓年代記』。原文はWikisourceで確認できます。</p>
<div class="hk-uirou-text">
<p>拙者親方と申すは、お立合の中に御存知のお方もござりましょうが、お江戸を発って二十里上方、相州小田原一色町をお過ぎなされて、青物町を登りへおいでなさるれば、欄干橋虎屋藤右衛門、只今は剃髪致して、円斎と名乗りまする。元朝より大晦日まで、御手に入れまする此の薬は、昔ちんの国の唐人、外郎という人、わが朝へ来り、帝へ参内の折から、此の薬を深く籠め置き、用ゆる時は一粒ずつ、冠の隙間より取り出す。依って其の名を帝より、「透頂香」と賜る。即ち文字には、頂き、透く、香いと書いて、とうちんこうと申す。</p>
<p>只今は此の薬、殊の外世上に弘まり、方々に似看板を出し、イヤ、小田原の、灰俵の、さん俵の、炭俵のと色々に申せども、平仮名をもって「ういろう」と記せしは親方円斎ばかり。もしやお立合の内に、熱海か塔の沢へ湯治にお出でなさるるか、又は伊勢参宮の折からは、必ず門違いなされまするな。お登りならば右の方、お下りなれば左側、八方が八つ棟、表が三つ棟玉堂造、破風には菊に桐の薹の御紋を御赦免あって、系図正しき薬でござる。</p>
<p>イヤ最前より家名の自慢ばかり申しても、御存じない方には、正身の胡椒の丸呑、白川夜船。さらば一粒食べかけて、その気味合をお目にかけましょう。先ず此の薬を、かように一粒舌の上に乗せまして、腹内へ納ますると、イヤどうも云えぬは、胃、心、肺、肝が健やかになりて、薫風咽より来り、口中微涼を生ずるが如し。魚鳥、茸、麺類の食合わせ、其の外、万病速攻あること神の如し。さて、此の薬、第一の奇妙には、舌の廻ることが、銭独楽が裸足で逃る。ひょっと舌が廻り出すと、矢も楯も堪らぬじゃ。</p>
<p>そりゃそりゃ、そらそりゃ。廻って来たわ、廻って来るわ。アワヤ咽、さたらな舌に、カ牙サ歯音。ハマの二つは唇の軽重、開口爽かに、あかさたなはまやらわ、おこそとのほもよろを、一つへぎへぎに、へぎほしはじかみ。盆豆、盆米、盆牛蒡。摘蓼、摘豆、摘山椒、書写山の社僧正。粉米の生噛、粉米の生噛、こん粉米の小生噛。繻子緋繻子、繻子繻珍、親も嘉兵衛、子も嘉兵衛、親嘉兵衛子嘉兵衛、子嘉兵衛親嘉兵衛。古栗の木の古切口。雨合羽か番合羽か。貴様の脚絆も皮脚絆、我等が脚絆も皮脚絆。尻皮袴のしっぽころびを、三針針長にちょと縫うて、縫うてちょとぶん出せ、河原撫子、野石竹。野良如来、野良如来、三野良如来に六野良如来。一寸先のお小仏にお蹴躓きゃるな。細溝に泥鰌にょろり。京の生鱈、奈良生学鰹、ちょと四、五貫目。お茶立ちょ、茶立ちょ、ちゃっと立ちょ、茶立ちょ、青竹茶筅でお茶ちゃっと立ちゃ。</p>
<p>来るわ来るわ何が来る、高野の山のおこけら小僧。狸百匹、箸百膳、天目百杯、棒八百本。武具馬具、ぶく、ばぐ、三武具馬具、合わせて武具馬具、六武具馬具。菊栗、きく、くり、三菊栗、合わせて菊栗、六菊栗。麦、ごみ、むぎ、ごみ、三麦ごみ、合わせて麦、ごみ、六麦ごみ。あの長押の長薙刀は、誰が長薙刀ぞ。向うの胡麻殻は荏の胡麻殻か、真胡麻殻か、あれこそ本の真胡麻殻。がらぴい、がらぴい風車。おきゃがれ小法師、おきゃがれ小法師、昨夜もこぼして、又こぼした。たあぷぽぽ、たあぷぽぽ、ちりから、ちりから、つったっぽ。たっぽたっぽ、一丁蛸、落たら煮て食を。煮ても焼いても食われぬものは、五徳、鉄弓、金熊童子に、石熊、石持、虎熊、虎鱚、中にも東寺の羅生門には、茨木童子が、うで栗五合、掴んでおむしゃる、かの頼光の膝元去らず。</p>
