<h3>1　外郎売を知る</h3>
<p>外郎売は、外郎という薬を売る商人の口上を題材にしたものです。独特な言葉や昔の表現、似た音が続く部分が多く、発音の練習にも使われています。</p>
<p>ただし、単なる早口言葉として扱うのではなく、<strong>長い言葉を明確に相手へ届けるための教材</strong>として考えてみましょう。</p>

<h3>2　まず、言葉の意味を知る</h3>
<p>外郎売には、普段の会話ではあまり使わない言葉や昔の表現が出てきます。意味が分からないまま音だけを覚えると、言葉がただの音の並びになってしまいます。</p>
<p>まず文章を読み、分からない言葉を調べて、何を伝えているのかを理解しましょう。</p>

<h3>3　一音ずつ明確に読む</h3>
<p>次は、言葉を一音ずつ丁寧に読んでみます。最初は、驚くほどゆっくりで構いません。</p>
<p>母音が曖昧になっていないか。子音が抜けていないか。口や舌がきちんと動いているか。第3章で練習したことを思い出しながら、一つひとつの音をつくります。</p>

<h3>4　音をつなげる</h3>
<p>一音ずつ明確にできるようになったら、今度は音をつなげます。一音ずつ区切ってしまうと、言葉が不自然になります。</p>
<p>音を明確にしながら、単語から文節へ、文節から文章へと自然につなげていきましょう。明瞭にすることと、強く発音することは同じではありません。</p>

<h3>5　意味を持って読む</h3>
<p>ここから、外郎売は「滑舌の練習」から「台詞」へ変わります。誰かに向かって話しているつもりで読んでみましょう。</p>
<p>何を伝えたいのか。誰に話しているのか。どんな状況なのか。言葉の意味を身体に入れながら読んでいきます。</p>

<h3>6　少しずつ速度を上げる</h3>
<p>明瞭に読めるようになったら、少しずつ速度を上げます。ゆっくり読む → 普通の速度で読む → 少し速く読む → さらに速く読む、というように、一段ずつ速度を上げていきます。</p>
<p><strong>音が崩れたら、一段階前の速度へ戻します。</strong></p>

<h3>7　「速く言う」と「急いで言う」は違う</h3>
<p>外郎売を練習していると、「もっと速く言わなければ」と思うことがあります。しかし、速く言うことと、急いで言うことは違います。</p>
<p>どれだけ速くても、音が聞こえ、言葉の意味が伝わらなければ、舞台では役に立ちません。<strong>速度は目的ではありません。</strong> 明瞭な言葉を保ったまま、必要な速度で話せることが大切です。</p>

<h3>8　相手へ届ける</h3>
<p>言葉は、自分の口の中で完成するものではありません。相手に届いて、初めて言葉として働きます。</p>
<p>まずは目の前の相手へ。次に少し離れた相手へ。そして劇場の奥へ。相手との距離を変えながら、言葉を届けてみましょう。</p>
<p>声をただ大きくするのではありません。<strong>言葉を相手へ向ける。</strong> その意識を持って読みます。</p>

<h3>9　外郎売を演じる</h3>
<p>最後は、滑舌の練習として外郎売を読むのをやめてみましょう。これまで練習してきたことを使って、一つの口上として演じます。</p>
<p>言葉の意味。相手。状況。身体。速度。そして、届ける方向。それらを一つにします。</p>
<p><strong>滑舌を見せるのではなく、言葉を届ける。</strong> それが、外郎売を演じるときの目標です。</p>

