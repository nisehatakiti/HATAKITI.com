</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-3　母音を明確にする</h2>
<p>母音は、言葉の響きと口の形を確認する基本です。</p>
</div>
<p>「あ・い・う・え・お」を一音ずつ発音し、口の形を丁寧に変えます。母音が曖昧になると、子音が聞こえていても言葉全体がぼやけてしまいます。</p>
