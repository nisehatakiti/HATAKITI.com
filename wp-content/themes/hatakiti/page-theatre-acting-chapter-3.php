<section class="hk-section">
<div class="hk-section-head">
<h2>はじめに</h2>
<p>滑舌は、早口で話すための技術ではありません。</p>
</div>
<p>舞台では、相手に向けた言葉が客席の最後列にも意味として届くことが求められます。そのためには、大きな声だけでなく、<strong>口・舌・顎・表情筋を適切に使い、音を明確にすること</strong>が必要です。</p>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>滑舌って、早口言葉を練習することなのかニャ？</p></div>
</div>
<div class="hk-nyakakichi-followup"><p>早口言葉は練習方法の一つです。まずはゆっくり、音を一つずつ明確にするところから始めます。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-1　滑舌のしくみ</h2>
<p>声が「言葉」になるまでには、いくつもの身体の働きがあります。</p>
</div>
<p>呼吸で生まれた息が声になり、その声を口の中で形づくることで、私たちは言葉を話します。滑舌では、<strong>息・声・口の形・舌・顎</strong>がつながっていることを意識します。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-01-how-words-are-formed.png' ) ); ?>" alt="声を口・舌・顎で明確な言葉にしていく滑舌のしくみ" loading="lazy">
<figcaption>できた声を、口・舌・顎の動きで明確な音と言葉へ形づくります。</figcaption>
</figure>
<div class="hk-panel">
<p><strong>滑舌の基本は「速さ」より「明瞭さ」です。</strong></p>
<p>ゆっくり話しても音が曖昧なら、聞き手には伝わりません。逆に、一つひとつの音が明確なら、速度が上がっても言葉を保ちやすくなります。</p>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-2　口・舌・表情筋を動かす</h2>
<p>発音の準備では、口だけでなく顔全体を固めないことも大切です。</p>
</div>
<p>顎を固める、唇があまり動かない、舌が動きにくい、頬や口角が固まっている。こうした状態では、音の形を細かく変えにくくなります。</p>
<p>ここでいう表情筋の使い方は、表情を大きくするための訓練ではありません。<strong>顔全体をゆるめ、発音に必要な部分を自由に動かせるようにする</strong>ことが目的です。</p>

<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-02-mouth-tongue-face-preparation.png' ) ); ?>" alt="顔・顎・唇・舌・頬と口角を使った発音準備" loading="lazy">
<figcaption>顔をゆるめ、顎・唇・舌・頬・口角を順番に動かして発音の準備をします。</figcaption>
</figure>
<div class="hk-articulation-prep">
<h3>発音のための準備</h3>
<div class="hk-articulation-steps">
<div><span>1</span><strong>顔をゆるめる</strong><small>眉間・頬・顎の余分な力を抜く</small></div>
<div><span>2</span><strong>顎を動かす</strong><small>軽く開閉し、固めない</small></div>
<div><span>3</span><strong>唇を動かす</strong><small>前後・左右へ自由に動かす</small></div>
<div><span>4</span><strong>舌を動かす</strong><small>前後・上下に無理なく動かす</small></div>
<div><span>5</span><strong>頬・口角を動かす</strong><small>顔全体を固めず音をつくる</small></div>
</div>
</div>

<div class="hk-exercise">
<h3>発音前の2分準備</h3>
<ol>
<li>顔全体の力を抜き、自然に口を閉じる。</li>
<li>顎を軽く開けたり閉じたりする。</li>
<li>唇を前へ出す、横へ引く、自然に戻す。</li>
<li>舌を前へ出す、戻す、左右へ動かす。</li>
<li>最後に「あ・い・う・え・お」を、顔全体を使ってゆっくり発音する。</li>
</ol>
<p><strong>ポイント：</strong>強く動かす必要はありません。動かしやすく、余分な力が残っていない状態をつくります。</p>
</div>

<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>顔を大きく動かせば、滑舌もよくなるのかニャ？</p></div>
</div>
<div class="hk-nyakakichi-followup"><p>大きく動かすことが目的ではありません。顎・唇・舌・頬などを固めず、必要な動きを自由にできることが大切です。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-3　母音を明確にする</h2>
<p>母音は、言葉の響きと口の形を確認する基本です。</p>
</div>
<p>「あ・い・う・え・お」を一音ずつ発音し、口の形を丁寧に変えます。母音が曖昧になると、子音が聞こえていても言葉全体がぼやけてしまいます。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-03-vowels.png' ) ); ?>" alt="母音の発声と口の形を示す図説" loading="lazy">
<figcaption>母音ごとの口の形を意識し、一音ずつ明確に発音します。</figcaption>
</figure>
<div class="hk-vowel-practice">
<div><strong>あ</strong><span>口を縦に開く</span></div>
<div><strong>い</strong><span>口角を横へ</span></div>
<div><strong>う</strong><span>唇を前へ</span></div>
<div><strong>え</strong><span>口を横に開き、頬・口角を使う</span></div>
<div><strong>お</strong><span>唇を丸くする</span></div>
</div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>母音って、口の形を変えることも練習なのかニャ？</p></div>
</div>
<div class="hk-nyakakichi-followup"><p>その通りです。口の形を丁寧に変えることで、音の違いがはっきりします。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-4　子音を明確にする</h2>
<p>子音は、言葉の輪郭をつくります。</p>
</div>
<p>「か・さ・た・は・ま・ら」などの各行を、一音ずつ明確に発音します。子音は、舌・唇・歯・口の形など、音によって使う場所が変わります。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-04-consonants.png' ) ); ?>" alt="日本語の各行でどこを使って子音をつくるかを示す図説" loading="lazy">
<figcaption>子音は、音によって舌・唇・息など使う場所が変わります。</figcaption>
</figure>
<div class="hk-consonant-grid">
<div><strong>か行</strong><span>舌の奥を使う</span></div>
<div><strong>さ行</strong><span>舌先と息を使う</span></div>
<div><strong>た行</strong><span>舌先を使う</span></div>
<div><strong>な行</strong><span>舌先と鼻への響き</span></div>
<div><strong>は行</strong><span>息の流れを使う</span></div>
<div><strong>ま行</strong><span>唇を使う</span></div>
<div><strong>ら行</strong><span>舌先を使う</span></div>
<div><strong>や・わ行</strong><span>口の形と息を使う</span></div>
</div>
<div class="hk-panel"><p><strong>全部を強く発音する必要はありません。</strong></p><p>音の特徴が分かる程度に明確にします。力任せにすると顎や喉まで固くなるので、必要な部分だけを動かします。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-5　音をつなげて言葉にする</h2>
<p>一音ずつ練習したら、音をつなげて自然な言葉にします。</p>
</div>
<p>滑舌練習では、一音ずつ明確にすることと、実際の言葉としてつなげることの両方が必要です。音を強調しすぎて不自然にならないよう、少しずつ通常の話し方へ戻します。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-05-connect-sounds-to-words.png' ) ); ?>" alt="一音から音の連続、単語、文章、台詞へ音をつなげる練習" loading="lazy">
<figcaption>明瞭さを保ったまま、一音から実際の言葉へつなげていきます。</figcaption>
</figure>
<div class="hk-articulation-flow">
<span>一音</span><b>→</b><span>音の連続</span><b>→</b><span>単語</span><b>→</b><span>文章</span><b>→</b><span>台詞</span>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-6　言葉の頭・途中・語尾を明確にする</h2>
<p>言葉は、最初から最後まで保ちます。</p>
</div>
<p>言葉の頭が弱いと聞き手は言葉の入り口をつかみにくくなります。途中の音が抜けると意味が変わり、語尾が消えると文の終わりが曖昧になります。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-06-word-beginning-middle-ending.png' ) ); ?>" alt="言葉の頭・途中・語尾を明確にする練習" loading="lazy">
<figcaption>言葉の入り口から最後の音まで、明瞭さを保ちます。</figcaption>
</figure>
<div class="hk-word-parts">
<div><strong>頭</strong><span>言葉の入り口を明確に</span></div>
<div><strong>途中</strong><span>音を落とさずにつなぐ</span></div>
<div><strong>語尾</strong><span>最後まで息と声を保つ</span></div>
</div>
<div class="hk-panel"><p><strong>語尾を「強くする」のではなく、語尾まで「存在させる」。</strong></p><p>舞台では、客席まで言葉が届くように、最後の音まで意識します。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-7　速く話しても崩さない</h2>
<p>速度を上げるのは、明瞭に話せるようになってからです。</p>
</div>
<p>文章や早口言葉を使って、ゆっくり → 一定の速度 → 少し速く、と段階を踏みます。音が崩れたら、一つ前の速度へ戻します。</p>
<figure class="hk-acting-figure">
<img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-articulation-07-speaking-fast-clearly.png' ) ); ?>" alt="明瞭さを保ったまま話す速度を段階的に上げる練習" loading="lazy">
<figcaption>ゆっくり・普通・少し速く、と段階的に速度を上げ、崩れたら一段階戻します。</figcaption>
</figure>
<div class="hk-exercise">
<h3>速度を変える練習</h3>
<ol>
<li>文章をゆっくり明瞭に読む。</li>
<li>一定のテンポで読む。</li>
<li>少しだけ速度を上げる。</li>
<li>音が崩れたら前の速度へ戻る。</li>
<li>もう一度、明瞭さを保てる速度から始める。</li>
</ol>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-8　台詞で滑舌を使う</h2>
<p>最後は、練習した滑舌を実際の台詞へつなげます。</p>
</div>
<p>まず台詞をゆっくり明確に読み、次に自然な速度へ戻します。その後、相手に話しかける意識、感情、身体の動きを加えます。</p>
<div class="hk-dialogue-flow">
<div><span>STEP 1</span><strong>ゆっくり読む</strong></div>
<div><span>STEP 2</span><strong>自然な速度へ</strong></div>
<div><span>STEP 3</span><strong>相手へ話す</strong></div>
<div><span>STEP 4</span><strong>感情・動きを加える</strong></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>3-9　劇場という空間に言葉を届ける</h2>
<p>滑舌は、口元だけの技術ではありません。</p>
</div>
<p>舞台では、相手役との距離だけでなく、客席の奥まで言葉が届くことを意識します。声量を上げることと、言葉を明確に届けることは別です。</p>
<div class="hk-panel">
<p><strong>息 → 声 → 音 → 言葉 → 相手 → 客席</strong></p>
<p>身体を使って息を送り、音を明確にし、その言葉を相手と空間へ届ける。これが舞台での滑舌です。</p>
</div>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div>
<div class="hk-nyakakichi-question"><p>大きな声なら、客席の奥まで言葉が届くのかニャ？</p></div>
</div>
<div class="hk-nyakakichi-followup"><p>声量だけではなく、息・響き・言葉の明瞭さ・声を向ける方向を使って届けます。</p></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>実践エチュード　滑舌を身体になじませる</h2>
<p>短い時間でも、順番を決めて繰り返します。</p>
</div>
<div class="hk-exercise"><h3>① 発音準備　2分</h3><p>顔をゆるめ、顎・唇・舌を動かしてから「あ・い・う・え・お」を発音します。</p></div>
<div class="hk-exercise"><h3>② 母音　3分</h3><p>「あ・い・う・え・お」を一音ずつ、次につなげて発音します。</p></div>
<div class="hk-exercise"><h3>③ 各行　3分</h3><p>か行・さ行・た行などを、一音ずつ明確に発音します。</p></div>
<div class="hk-exercise"><h3>④ 文章　5分</h3><p>短い文章を、ゆっくり → 一定の速度 → 少し速く、の順に読みます。</p></div>
<div class="hk-exercise"><h3>⑤ 早口言葉　5分</h3><p>速さより明瞭さを優先します。音が崩れたら速度を戻します。</p></div>
<div class="hk-exercise"><h3>⑥ 台詞　5分</h3><p>実際の台詞を、ゆっくり明確に読む → 自然な速度へ戻す → 相手へ話す、の順に練習します。</p></div>
<div class="hk-exercise"><h3>⑦ 空間　5分</h3><p>客席の奥まで言葉が届く方向を意識しながら、喉で押さずに発声します。</p></div>
</section>

<section class="hk-section">
<div class="hk-panel hk-summary">
<h3>第3章まとめ</h3>
<p><strong>身体を準備する → 母音を明確にする → 子音を明確にする → 音をつなげる → 速度を上げる → 台詞にする → 空間へ届ける。</strong></p>
<p>滑舌は、早口になるための技術ではありません。口・舌・顎・顔を自由に使い、言葉を明確にし、相手と劇場という空間へ届けるための技術です。</p>
</div>
</section>

