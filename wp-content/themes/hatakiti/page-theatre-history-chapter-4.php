        <p>劇団、俳優、劇場、劇作家、衣装や舞台装置など、多くの人が関わる仕組みが生まれました。観客の人気も、劇団や俳優の活動を左右するようになります。</p>
        <p>ここから演劇は、芸術であると同時に、<strong>人・場所・お金・技術が結びついた社会的な仕事</strong>としても発展していくことになります。</p>

