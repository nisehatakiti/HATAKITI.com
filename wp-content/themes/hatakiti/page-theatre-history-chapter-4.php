        <p>劇団を組み、各地を移動しながら公演する俳優たちも現れます。俳優には、台詞を覚える力だけでなく、声、身体、身振り、観客との距離を使って場を成立させる力が求められました。</p>
        <p>ここで、演劇は「誰かが物語を演じる行為」から、<strong>多くの専門家が関わる仕事</strong>へと、さらに一歩進んでいきます。</p>
    </section>

    <section class="hk-section">
