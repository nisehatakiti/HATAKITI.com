<section class="hk-section">
<div class="hk-section-head"><h2>15-1　欲求とは何か</h2><p>人物の心の奥にある「こうしたい」「こうなりたい」という強い求めを考えます。</p></div>
<p>欲求とは、人物が心の奥で「こうしたい」「こうなりたい」と強く求めているものです。目的が「何をしようとしているのか」だとすれば、欲求は「なぜ、それを求めているのか」に近いものです。</p>
<p>たとえば、同じ「ここにいてください」という台詞でも、「愛されたい」から言うのか、「相手を失いたくない」から言うのか、「自分が一人になるのが怖い」から言うのかによって、行動の意味は変わります。欲求は、目的や行動、言葉のエネルギーの源になります。</p>
<p>演技では、人物の欲求を決めて感情を作るのではなく、人物が何を求め、何を守ろうとしているのかを具体的に考えることから始めます。</p>
