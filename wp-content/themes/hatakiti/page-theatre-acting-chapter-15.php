</section>

<section class="hk-section">
<div class="hk-section-head"><h2>15-2　欲しいものを考える</h2><p>人物が本当に欲しいものを具体的にすると、目的や行動が見えてきます。</p></div>
<p>「欲しいもの」と言っても、物だけを指すわけではありません。愛されたい、認められたい、自由になりたい、安心したい、誰かとつながっていたい、もっと知りたい――人によって求めるものは違います。</p>
<p>人物について考えるときは、「この人は何が欲しいのか？」をできるだけ具体的にしてみましょう。欲しいものが具体的になると、そのために何をするのか、誰に近づくのか、何を避けるのかが考えやすくなります。</p>
<p>第14章の「目的」は、人物が今しようとしていることでした。第15章では、その目的の奥にある「なぜ、それを求めるのか」を掘り下げます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-15-2-what-they-want.png' ) ); ?>" alt="欲しいものを考える図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-thinking.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>欲しいものが分かると、その人物が何をするのか考えやすくなるんだニャ。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>15-3　失いたくないもの</h2><p>人は「得たいもの」だけでなく、「失いたくないもの」にも強く動かされます。</p></div>
<p>人物を考えるときには、「何が欲しいのか」だけでなく、「何を失いたくないのか」も重要です。大切な人、信頼、居場所、自由、役割、安心、自分自身の価値など、人によって守りたいものは違います。</p>
<p>失いたくないものが見えてくると、人物がなぜそこまで必死になるのか、その行動の理由が見えてきます。普段は穏やかな人物でも、大切なものを失いそうになった瞬間には、強い行動をとるかもしれません。</p>
<p>「この人物は、何を失ったら一番困るのか？」と考えてみましょう。それは、その人物の弱さや執着、相手との関係を知る手がかりになります。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-15-3-what-they-dont-want-to-lose.png' ) ); ?>" alt="失いたくないものを考える図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-interested.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>「欲しいもの」だけじゃなくて、「失いたくないもの」も人物を動かすんだニャ。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>15-4　恐れているもの</h2><p>人物が何を恐れているのかを知ると、行動の理由が見えてきます。</p></div>
<p>欲求と反対側から人物を見る方法もあります。それが「恐れているもの」を考えることです。人物は、起こってほしくないことや、避けたいことからも強く動かされます。</p>
<p>たとえば、拒絶されること、失敗すること、大切な人を失うこと、孤独になること、傷つくこと、自分ではどうにもできない状況になること。何を恐れているかによって、同じ場面でも選ぶ行動は変わります。</p>
<p>恐れを考えるときも、「怖い」という感情だけで終わらせません。「何が起きるのが怖いのか」「それが起きると、この人物は何を失うのか」まで具体的にしてみましょう。すると、逃げる、隠す、攻撃する、守るといった行動につながっていきます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-15-4-what-they-fear.png' ) ); ?>" alt="恐れているものと行動の関係を示す図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-alert.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>恐れているものが分かると、逃げたり隠したりする理由まで見えてくるんだニャ。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>15-5　欲求と行動</h2><p>欲求は、目的を生み、その目的を達成するための行動につながります。</p></div>
<p>欲求は、そのまま舞台上の動きになるわけではありません。まず「何を求めているのか」があり、それを叶えるために目的を持ち、具体的な行動を選びます。</p>
<p>たとえば「愛されたい」という欲求がある人物なら、相手に近づく、話しかける、助ける、喜ばせるなど、さまざまな行動が考えられます。一方、「傷つきたくない」という欲求なら、距離をとる、隠す、拒むといった行動になるかもしれません。</p>
<p>大切なのは、欲求を顔や声で直接表現しようとしないことです。欲求を持った人物として、相手に何をしようとしているのかを考え、行動してください。行動が具体的になると、欲求は結果として舞台に見えてきます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-15-5-desire-and-action.png' ) ); ?>" alt="欲求と行動の関係を示す図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-practice.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>欲求を直接演じるんじゃなくて、欲求から生まれた行動を演じるんだニャ。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>15-6　欲求がぶつかる</h2><p>人物同士の欲求がぶつかると、対立や緊張が生まれ、物語が動きます。</p></div>
<p>一人の人物の中にも、複数の欲求があることがあります。「自由になりたい」と思いながら「誰かに認められたい」と思っている、といった具合です。</p>
<p>さらに、相手にも別の欲求があります。自分は「真実を知りたい」のに、相手は「知られたくない」と思っている。自分は「一緒にいたい」のに、相手は「一人になりたい」と思っている。こうした欲求のぶつかり合いが、対立や緊張を生みます。</p>
<p>演技では、自分の欲求だけでなく、相手が何を求め、何を守ろうとしているのかも考えましょう。欲求がぶつかった結果、二人の行動がどう変化するのかを追うことで、関係性や場面の動きが見えてきます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-15-6-conflicting-desires.png' ) ); ?>" alt="欲求がぶつかることで対立が生まれる図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-surprised.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>お互いの欲求がぶつかるから、場面に緊張が生まれるんだニャ！</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>実践エチュード</h2><p>欲求を目的と行動につなげて、一人の人物をつくってみます。</p></div>
<div class="hk-exercise">
<h3>欲求から人物をつくる　10分</h3>
<ol>
<li>「愛されたい」「認められたい」「自由になりたい」など、人物の欲求を一つ決める。</li>
<li>その人物が失いたくないものを一つ決める。</li>
<li>その人物が恐れていることを一つ決める。</li>
<li>欲求を叶えるための目的を一つ決める。</li>
<li>目的のために、相手へ具体的な行動をする。</li>
<li>相手にも別の欲求を設定し、二人の欲求をぶつけてみる。</li>
<li>最後に、欲求が変化したか、行動がどう変わったかを振り返る。</li>
</ol>
<p><strong>ポイント：</strong>「欲求を表現しよう」としないこと。欲求を持った人物として、相手に何をしようとしているのかを演じてみましょう。</p>
</div>
