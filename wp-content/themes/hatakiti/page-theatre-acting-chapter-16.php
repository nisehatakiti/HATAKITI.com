</section>

<section class="hk-section">
<div class="hk-section-head"><h2>16-2　相手の言葉を受ける</h2><p>台詞を聞くだけで終わらず、その言葉に込められた意味や感情、状況まで受け取ります。</p></div>
<p>相手が「大丈夫だよ」と言ったとしても、安心して言っているのか、無理をしているのか、怒りながら言っているのかによって、受け取る意味は変わります。台詞そのものだけでなく、言い方や表情、間、これまでのやり取りにも注意を向けます。</p>
<p>相手の言葉を受けたら、すぐに自分の台詞を言おうとしなくて構いません。一度受け止め、その言葉が自分に何を起こしたのかを感じてから返します。すると、台詞が決められた順番で出てくるのではなく、相手とのやり取りから生まれてきます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-16-2-receive-the-other-words.png' ) ); ?>" alt="相手の言葉を受け取る流れを示す図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-thinking.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>すぐに返すんじゃなくて、相手の言葉をちゃんと受け止めるんだニャ。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>16-3　相手によって自分が変わる</h2><p>同じ自分でも、相手が変われば、声・表情・姿勢・距離・言葉の選び方が変わります。</p></div>
<p>人は誰と話しているかによって、自然に振る舞いが変わります。友人には気楽に話せても、上司には緊張する。苦手な人には距離を取る。好きな人には普段と違う表情が出る。演技でも同じように、相手との関係によって人物の反応は変化します。</p>
<p>大切なのは「この人物はこういう人だから」と最初から決めてしまわないことです。相手の存在を受け、その人から何を感じたかによって、自分の身体や言葉が変わることを試してみましょう。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-16-3-change-by-the-other.png' ) ); ?>" alt="相手によって自分の反応が変わることを示す図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-surprised.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>同じ人物でも、相手が変わるとこんなに反応が変わるんだニャ！</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>16-4　人物同士の関係</h2><p>友人、家族、恋人、上司と部下など、関係性によって言葉・距離・態度・声のトーンが変わります。</p></div>
<p>台本を読むときは、人物の性格だけでなく、登場人物同士がどんな関係なのかを考えてみましょう。初対面なのか、長い付き合いなのか、信頼しているのか、警戒しているのか、立場に差があるのかによって、同じ台詞でも意味が変わります。</p>
<p>関係性は、台詞に直接書かれているとは限りません。相手との距離、目を合わせるか、どちらが話を主導するか、どのくらい丁寧な言葉を使うかなど、身体や声にも表れます。関係を具体的に考えることで、人物同士のやり取りが見えてきます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-16-4-relationship-between-characters.png' ) ); ?>" alt="人物同士の関係性と演技への影響を示す図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-thinking.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>関係が違えば、同じ言葉でも言い方や距離まで変わるんだニャ。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>16-5　関係が変化する瞬間</h2><p>言葉・行動・沈黙・出来事などをきっかけに、人物同士の関係は変化します。</p></div>
<p>物語の中で、関係性は最初から最後まで同じとは限りません。信頼していた相手を疑うようになったり、対立していた相手を理解したり、離れてしまったりすることがあります。</p>
<p>演技で大切なのは、関係が変わった「後」だけを表現することではありません。何がきっかけになったのか、その瞬間に相手から何を受け取ったのかを考えることです。小さな言葉や沈黙が、二人の関係を変えることもあります。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-16-5-relationship-change.png' ) ); ?>" alt="人物同士の関係が変化するきっかけと流れを示す図" loading="lazy"></figure>
