</section>

<section class="hk-section">
<div class="hk-section-head"><h2>16-6　相手と一緒に場面をつくる</h2><p>相手の言葉や行動を受け、自分が変わり、その変化をまた相手に返して場面をつくります。</p></div>
<p>演技は、一人で完成させたものを相手の前で見せるだけではありません。相手が何かをする、自分がそれを受ける、自分が反応する、その反応によって相手も変わる――この繰り返しの中で、場面が少しずつ形になっていきます。</p>
<p>だからこそ、最初から最後まで自分の演技を決めすぎないことも大切です。相手から何が来るかを受け取れる余白を残し、その場で起きたことに反応してください。二人のやり取りが続くことで、台本に書かれていない小さな変化も舞台上に生まれます。</p>
<figure class="hk-acting-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-16-6-create-scene-together.png' ) ); ?>" alt="相手と一緒に場面をつくる流れを示す図" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-happy.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>相手と受け渡しを続けると、二人で場面が生まれてくるんだニャ！</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>実践エチュード</h2><p>相手を見るところから始めて、受ける・反応する・関係を変化させるところまでつなげます。</p></div>
<div class="hk-exercise">
<h3>相手と一緒に場面をつくる　10分</h3>
<ol>
<li>二人組になり、簡単な状況を一つ決める。</li>
<li>まず相手の表情・声・身体の変化をよく見る。</li>
<li>相手の言葉をすぐに返さず、一度受け止める。</li>
<li>受け取ったものによって、自分の表情・声・身体・言葉を変える。</li>
<li>相手の反応をもう一度受け、さらに行動を変える。</li>
<li>途中で関係が変わる出来事を一つ入れてみる。</li>
<li>最後に、どの瞬間に相手との関係が変化したか振り返る。</li>
</ol>
<p><strong>ポイント：</strong>相手を思い通りに動かそうとせず、相手から来たものを受けて自分を変えてみましょう。</p>
</div>
