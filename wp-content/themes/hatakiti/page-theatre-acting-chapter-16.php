<section class="hk-section">
<div class="hk-section-head"><h2>16-1　相手を見る</h2><p>相手の顔だけでなく、表情・身体・声・言葉・間・視線・変化などから、相手に起きていることを受け取ります。</p></div>
<p>演技では、自分が何をするかだけを考えていると、相手とのやり取りが一方通行になってしまいます。まず相手をよく見て、今どんな表情をしているのか、身体がどう動いたのか、声の大きさや速さが変わったのかを観察します。</p>
<p>見ることは、相手の気持ちを勝手に決めつけることではありません。目の前に起きている変化を受け取り、「今、相手に何が起きたのだろう」と注意を向けることです。そこから自分の反応が生まれます。</p>
