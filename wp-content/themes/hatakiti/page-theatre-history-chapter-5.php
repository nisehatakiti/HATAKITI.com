    <section class="hk-section">
        <div class="hk-section-head"><h2>5-10　日本では「新劇」が生まれる</h2></div>
        <p>日本でも明治から大正にかけて、西洋の近代演劇を学び、日本の舞台を新しくしようとする動きが生まれました。</p>
        <p>坪内逍遥や小山内薫など、多くの人々が西洋の戯曲や演劇論を紹介し、歌舞伎などとは異なる新しい演劇を模索しました。後に「新劇」と呼ばれる流れにつながっていきます。</p>
        <p>ここでも、海外の演劇をそのままコピーしたのではありません。日本の社会や俳優、劇場の状況に合わせながら、新しい演劇の形が試されました。</p>
    </section>

    <section class="hk-section">
        <div class="hk-section-head"><h2>5-11　演劇は「再現」から「解釈」へ</h2></div>
        <p>近代演劇では、台本に書かれた物語をそのまま舞台に再現するだけではなく、作品をどう解釈するかが大きなテーマになります。</p>
        <p>同じ戯曲でも、演出家によって舞台の見え方が変わる。俳優によって人物の見え方が変わる。舞台美術や照明によって、同じ場面の意味が変わる。</p>
        <p>つまり、演劇は<strong>戯曲だけで完成するものではなく、上演によって新しい意味が生まれる</strong>という考え方が強くなっていきました。</p>
