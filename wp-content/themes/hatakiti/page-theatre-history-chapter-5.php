    <section class="hk-section">
        <div class="hk-section-head"><h2>5-2　舞台に「今の社会」が登場する</h2></div>
        <p>以前の演劇では、神話や歴史上の人物、王侯貴族などを扱う作品も多くありました。しかし近代になると、現代の社会で生きる普通の人々を描く作品が増えていきます。</p>
        <p>家族、結婚、仕事、お金、階級、男女の関係など、観客自身の生活とつながる題材が舞台に登場します。</p>
        <p>舞台は遠い昔の世界を見せるだけではなく、<strong>「今、自分たちが生きている社会はどうなっているのか」</strong>を考える場所にもなりました。</p>
        <figure class="hk-history-diagram"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/history/history-chapter5-02-society-on-stage.png' ) ); ?>" alt="近代演劇で日常生活や社会問題が舞台に登場する変化を説明する図" loading="lazy"></figure>

    </section>

    <section class="hk-section">
        <div class="hk-section-head"><h2>5-3　「現実らしさ」を求める</h2></div>
        <p>近代演劇では、舞台をできるだけ現実らしく見せようとする考え方が強くなります。</p>
        <p>たとえば居間を舞台にするなら、実際の家のように家具を置く。登場人物が食事をするなら、本当に食器を使う。衣装も、その人物の生活や時代に合うものを選ぶ。</p>
        <p>観客が「これは舞台装置だ」と意識するのではなく、<strong>そこに本当に生活している人がいるように見せる</strong>ことが目指されました。</p>
        <div class="hk-nyakakichi">
            <div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-thinking.png' ) ); ?>" alt="リアルな舞台について考えるにゃかきち" loading="lazy"></div>
