<section class="hk-section">
<div class="hk-section-head">
<h2>4-1　身体を知る</h2>
<p>動かす前に、自分の身体がどうなっているのかを知ります。</p>
</div>
<p>演技で使う身体は、ただ鍛えればよいものではありません。どこが動き、どこに力が入り、どこが動きにくいのかを自分で感じられることが大切です。</p>
<p>身体の感覚が分かれば、動きを意識的に変えられるようになります。</p>
<div class="hk-exercise">
<h3>身体をスキャンする</h3>
<ol>
<li>立ったまま、足裏から頭まで順番に意識する。</li>
<li>力が入っている場所、抜けている場所を探す。</li>
<li>左右で感覚が違うところを見つける。</li>
<li>一度全身を軽く緊張させ、その後ゆっくり力を抜く。</li>
</ol>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>4-2　力を入れる・抜く</h2>
<p>身体を自由にするとは、いつも力を抜いていることではありません。</p>
</div>
<p>必要な瞬間には力を使い、必要がなくなったらすぐに手放す。その切り替えができると、身体は動きやすくなります。</p>
<p>力を入れ続けていると、動きが遅くなったり、呼吸や声まで固くなったりします。</p>
<div class="hk-exercise">
<h3>緊張と解放</h3>
<ol>
<li>手を強く握り、数秒その状態を感じる。</li>
<li>手を開き、力が抜けていく感覚を感じる。</li>
<li>肩、顔、腹、脚でも同じことを行う。</li>
<li>最後に全身を一度固め、そこから一気に力を抜く。</li>
</ol>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>4-3　身体を分けて動かす</h2>
<p>身体を一つの塊として動かさず、部分ごとの動きを感じます。</p>
</div>
<p>頭、胸、骨盤、腕、手、膝など、身体の一部分を意識して動かしてみましょう。</p>
<p>身体を分けて感じられるようになると、同じ「歩く」動作でも、どこを先に動かすかによって違う動きをつくれることが分かります。</p>
<div class="hk-exercise">
<h3>身体のどこから動くか</h3>
<p>頭が先に進む。胸が先に進む。骨盤が先に進む。膝が先に進む。それぞれの身体の部分をリード役にして歩いてみます。</p>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>4-4　重さ・大きさ・動きを表現する</h2>
<p>実際の重さや大きさではなく、観客にどう見えるかを身体でつくります。</p>
</div>
<p>舞台では、軽い箱を重い箱として見せたり、小さなものを大きく扱ったりすることがあります。観客は実際の重さを知りません。身体の使い方から、その重さや大きさを感じ取ります。</p>
<p>例えば、軽い箱を重く見せるなら、持ち上げる前に身体を準備し、重さを受け止め、脚や背中を使ってゆっくり持ち上げます。持ち上げた後も、重さを支えている身体を続けます。</p>
<div class="hk-panel">
<p><strong>重い・軽い　／　大きい・小さい　／　速い・遅い　／　硬い・柔らかい</strong></p>
<p>同じ動作でも、身体の条件を変えるだけで、観客に伝わる印象は大きく変わります。</p>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>4-5　動きの質を変える</h2>
<p>動作そのものだけでなく、動き方にも違いをつくります。</p>
</div>
<p>同じ「腕を上げる」という動作でも、急に上げる、ゆっくり上げる、ためらいながら上げる、重いものを持ち上げるように上げるなど、動きの質を変えることができます。</p>
<p>演技では、何をするかだけでなく、<strong>どうするか</strong>が人物や状況を表します。</p>
<div class="hk-exercise">
<h3>一つの動作を変える</h3>
<ol>
<li>腕を普通に上げる。</li>
<li>できるだけゆっくり上げる。</li>
<li>何かに引っ張られるように上げる。</li>
<li>とても重いものを持ち上げるように上げる。</li>
<li>今度は、とても軽いものを扱うように上げる。</li>
</ol>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>4-6　身体から人物をつくる</h2>
<p>人物の性格や状態を、身体の使い方から発見してみます。</p>
</div>
<p>人物を「明るい人」「怖い人」のように頭だけで決めるのではなく、身体の条件を変えてみます。</p>
<p>胸を開く。身体を小さくする。歩幅を広くする。手を大きく使う。視線を下げる。動きを止める。</p>
<p>身体の変化によって、人物の印象も変わります。そこから、その人物がどんな人なのかを考えてみましょう。</p>
<div class="hk-panel">
<p><strong>身体を変える → 印象が変わる → 人物を発見する</strong></p>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>4-7　身体と呼吸・声をつなげる</h2>
<p>身体が動くとき、呼吸と声も身体の一部として扱います。</p>
</div>
<p>身体を固めたまま声だけを出そうとすると、呼吸も声も動きにくくなります。</p>
<p>歩く、止まる、向きを変える、手を伸ばす。そうした動きの中で呼吸を続け、そのまま声や言葉につなげてみましょう。</p>
<div class="hk-exercise">
<h3>動きながら声を使う</h3>
<ol>
<li>自然に歩く。</li>
<li>歩きながら息を吐く。</li>
<li>歩きながら「あー」と声を出す。</li>
<li>止まった瞬間に短い言葉を言う。</li>
<li>再び歩き、動きながら台詞を一言話す。</li>
</ol>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>実践エチュード</h2>
<p>身体の感覚を使って、同じ動作に違う質を与えてみます。</p>
</div>
<div class="hk-exercise">
<h3>一つの箱を変えてみる　10分</h3>
<ol>
<li>目の前に箱があると想像する。</li>
<li>普通の重さとして持ち上げる。</li>
<li>とても重い箱として持ち上げる。</li>
<li>とても軽い箱として持ち上げる。</li>
<li>とても大きな箱として扱う。</li>
<li>手のひらに乗るほど小さな箱として扱う。</li>
<li>最後に、台詞を一言加えて同じ動作を行う。</li>
</ol>
<p><strong>ポイント：</strong>身体を大げさに動かすことが目的ではありません。重さ、大きさ、速さを身体全体で受け取り、その違いが観客に見えるようにします。</p>
</div>
</section>

<section class="hk-section">
<div class="hk-panel hk-summary">
<h3>第4章まとめ</h3>
<p><strong>身体を知る → 力を調整する → 身体を分けて動かす → 重さや大きさを表現する → 動きの質を変える → 人物につなげる。</strong></p>
<p>身体は、ただ動くためのものではありません。身体の使い方そのものが、人物や状況、物の存在を観客に伝える表現になります。</p>
<p>次の第5章では、身体の土台となる「姿勢」をさらに詳しく扱います。</p>
</div>
</section>

