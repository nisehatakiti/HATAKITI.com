<div class="hk-breath-types">
<article>
<h3>胸式呼吸</h3>
<p>胸や肋骨の動きを中心に息をする呼吸です。肩や胸が動きやすく、緊張すると浅くなりやすい傾向があります。</p>
</article>
<article>
<h3>腹式呼吸</h3>
<p>横隔膜の動きによって、お腹まわりが動くことを感じやすい呼吸です。息を吸うとお腹まわりが広がり、吐くと自然に戻ります。</p>
</article>
</div>

<div class="hk-panel">
<p><strong>胸式呼吸と腹式呼吸、どちらが正解？</strong></p>
<p>演技では、どちらか一方だけを使えばよいわけではありません。大切なのは、胸・肋骨・横隔膜・お腹など身体全体を使って、必要な量の息を自由に扱えることです。</p>
</div>

