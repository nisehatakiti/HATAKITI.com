<section class="hk-section"><div class="hk-section-head"><h2>1-1　呼吸は演技の土台</h2><p>呼吸は生命活動であると同時に、舞台上の身体と声を支える土台です。</p></div>
<p>緊張すると息が浅くなったり、言葉を出そうとして息を止めたりします。逆に、呼吸が自由になると身体の動きや声にも変化が生まれます。</p>
<div class="hk-panel"><p><strong>深く吸うことだけが正解ではありません。</strong></p><p>大切なのは、必要なときに吸えて、必要なときに吐けること。そして、演技中に呼吸を自分で観察できることです。</p></div></section>
<section class="hk-section"><div class="hk-section-head"><h2>1-2　まず「吐く」</h2><p>呼吸を整えようとして、大きく吸おうとしすぎる必要はありません。</p></div>
<p>まず自然に息を吐きます。吐いたあとに身体が必要とする分だけ自然に吸う。これを繰り返して、呼吸を止めない感覚を覚えます。</p>
<div class="hk-exercise"><h3>1分呼吸観察</h3><ol><li>立って普段どおりに呼吸する。</li><li>息を吐くときだけ意識する。</li><li>肩、顎、胸、腹のどこが動いているか観察する。</li><li>息を吐いたあと、次の吸気を待つ。</li><li>呼吸を大きくしようとせず、自然に戻す。</li></ol></div></section>
<section class="hk-section"><div class="hk-section-head"><h2>1-3　身体を固めない</h2></div>
<p>声を出すときに顎を固める、息を吸うときに肩を上げる、緊張すると腹部を固める。こうした癖があると、呼吸と声の自由を失いやすくなります。</p>
<p>力を抜くことは、身体をふにゃふにゃにすることではありません。<strong>必要な力だけを使い、余分な力を手放せること</strong>が重要です。</p></section>
<section class="hk-section"><div class="hk-section-head"><h2>1-4　動きながら呼吸する</h2></div>
<div class="hk-exercise"><h3>歩く呼吸</h3><ol><li>ゆっくり歩く。</li><li>歩く速さを変えても呼吸を止めない。</li><li>立ち止まる、方向を変える、しゃがむなど動きを加える。</li><li>動きが変わった瞬間に、呼吸がどう変化したか観察する。</li></ol><p>演技では「動いてから呼吸する」のではなく、呼吸しながら動き、動きながら呼吸します。</p></div></section>
<section class="hk-section"><div class="hk-section-head"><h2>1-5　声につなげる</h2></div>
<p>息を吐く流れに短い声を乗せます。「あ」「う」「ん」など、無理のない音から始めます。</p>
<div class="hk-exercise"><h3>息から声へ</h3><ol><li>自然に息を吐く。</li><li>吐く息の途中に小さな「あ」を乗せる。</li><li>声を大きくするのではなく、息と声がつながっている感覚を探す。</li><li>最後に短い言葉を一つ発する。</li></ol></div></section>
<section class="hk-section"><div class="hk-panel hk-summary"><h3>第1章まとめ</h3><p><strong>呼吸をコントロールする前に、呼吸を観察する。</strong></p><p>吐く、動く、声にする。呼吸が身体と声をつなぐ感覚を身につけることが、次の「発声」につながります。</p></div></section>
