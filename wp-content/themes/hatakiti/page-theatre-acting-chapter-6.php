<section class="hk-section">
<div class="hk-section-head">
<h2>6-1　まず、自分の歩き方を知る</h2>
<p>歩くことを意識して、自分の普段の歩き方を観察します。</p>
</div>
<p>歩くことは、普段ほとんど意識せずに行っている動作です。だからこそ、演技に使う前に、自分がどのように歩いているのかを知ることから始めます。</p>
<p>歩く速さ、歩幅、足の運び方、腕の動き、視線、身体の向き、歩き始め方、止まり方。人によって、さまざまな癖があります。</p>
<p>ここでは「正しい歩き方」を作ることが目的ではありません。まず、<strong>自分にはどんな歩き方の特徴があるのかを知る</strong>ことが大切です。</p>
<div class="hk-exercise">
<h3>自分の歩き方を観察する</h3>
<ol>
<li>普段どおりに歩く。</li>
<li>少しゆっくり歩いてみる。</li>
<li>歩幅や腕の動きを意識する。</li>
<li>もう一度、何も意識せず歩く。</li>
<li>最初の歩き方との違いを感じる。</li>
</ol>
</div>
