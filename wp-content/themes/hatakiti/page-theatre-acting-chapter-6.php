</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>6-2　速度を変える</h2>
<p>歩く速さが変わると、身体の使い方も変わります。</p>
</div>
<p>まず、ゆっくり、普通、速いという三つの速度で歩いてみます。</p>
<p>速く歩くときは、ただ足を速く動かすだけではありません。呼吸、視線、腕の動き、歩幅など、身体全体の使い方も変わってきます。</p>
<p>「速い＝急いでいる人」と決めつける必要はありません。まずは、<strong>速度が変わると自分の身体がどう変化するのか</strong>を感じてみましょう。</p>
<div class="hk-exercise">
<h3>速度だけを変えて歩く</h3>
<ol>
<li>普通の速度で歩く。</li>
<li>半分くらいの速度で歩く。</li>
<li>普通の速度に戻る。</li>
<li>少し速く歩く。</li>
<li>速度を変えたとき、身体のどこが変わったか確認する。</li>
</ol>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-06-2-walking-speed.png' ) ); ?>" alt="図説②　速度を変える" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>速く歩くと、足だけじゃなくて身体全体が変わるんだね。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>6-3　歩幅を変える</h2>
<p>歩幅を変えると、同じ人の歩き方でも見え方が変わります。</p>
</div>
<p>同じ速度で歩いていても、歩幅が違えば身体の動きは変わります。小さな歩幅、普段の歩幅、大きな歩幅を順番に試してみましょう。</p>
<p>さらに、歩いている途中で歩幅を変えてみます。歩幅が変わった瞬間に、自分の身体の使い方や見え方がどう変化したかを感じます。</p>
<p>大きな歩幅だから元気、小さな歩幅だから弱い、と決めつける必要はありません。<strong>歩幅を変えたことで何が変わったのかを観察する</strong>ことが目的です。</p>
<div class="hk-exercise">
<h3>歩幅だけを変えて歩く</h3>
<ol>
<li>普段の歩幅で歩く。</li>
<li>歩幅を小さくする。</li>
<li>普段の歩幅に戻す。</li>
<li>歩幅を大きくする。</li>
<li>途中で歩幅を変えてみる。</li>
<li>見ている人からどう見えたか確認する。</li>
</ol>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-06-3-stride.png' ) ); ?>" alt="図説③　歩幅を変える" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>同じ速さでも、歩幅が違うと歩き方そのものが違って見えるね。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>6-4　方向と向きを変える</h2>
<p>どこへ向かうのかによって、歩く身体の使い方も変わります。</p>
</div>
<p>歩くということは、ただ前へ進むことではありません。舞台では、どこへ向かうのか、誰に近づくのか、誰から離れるのかという方向そのものが、人物の状態を見せることがあります。</p>
<p>まっすぐ歩く、曲がる、途中で方向を変える、誰かへ向かう、誰かから離れる。いろいろな方向へ歩きながら、身体の向きや視線がどう変わるかを感じてみます。</p>
<p>ここではまだ人物の演技を作り込む必要はありません。まず、<strong>方向を変えると自分の身体の使い方がどう変わるか</strong>を知ります。</p>
<div class="hk-exercise">
<h3>方向を変えて歩く</h3>
<ol>
<li>舞台をまっすぐ歩く。</li>
<li>途中で90度方向を変える。</li>
<li>急に方向を変える。</li>
<li>誰かに向かって歩く。</li>
<li>誰かから離れるように歩く。</li>
</ol>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-06-4-direction.png' ) ); ?>" alt="図説④　方向と向きを変える" loading="lazy"></figure>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>6-5　身体の質を変える</h2>
<p>身体の状態を変えると、自然に歩き方も変化します。</p>
</div>
<p>歩き方を変えるとき、足の動きだけを変える必要はありません。身体全体の状態を変えることで、歩き方も変わります。</p>
<p>軽く、重く、硬く、柔らかく、疲れて、急いで、周囲を警戒して。さまざまな状態を想像しながら歩いてみます。</p>
<p>これらを「演技の型」として覚えるのではありません。<strong>身体の状態が変わることで、歩き方が変わり、見え方も変わる</strong>という関係を体験します。</p>
<div class="hk-exercise">
<h3>身体の質を変えて歩く</h3>
<ol>
<li>普通に歩く。</li>
<li>身体を軽く感じて歩く。</li>
<li>身体を重く感じて歩く。</li>
<li>身体を硬くして歩く。</li>
<li>身体を柔らかくして歩く。</li>
<li>自分で一つ状態を決めて歩く。</li>
</ol>
</div>
<figure class="hk-acting-figure"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/acting/acting-06-5-body-quality.png' ) ); ?>" alt="図説⑤　身体の質を変える" loading="lazy"></figure>
<div class="hk-nyakakichi"><div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち" loading="lazy"></div><div class="hk-nyakakichi-question"><p>足の動かし方を変えなくても、身体の感じ方で歩き方が変わるんだね。</p></div></div>
</section>

<section class="hk-section">
<div class="hk-section-head">
<h2>6-6　歩き方で人物をつくる</h2>
<p>ここまで変えてきた歩き方を、人物の状態や目的につなげます。</p>
</div>
<p>歩く速さ、歩幅、方向、身体の質。ここまでに試したものを組み合わせると、歩き方から人物を作ることができます。</p>
<p>例えば「待ち合わせ場所へ向かっている」という同じ状況でも、楽しみにしているのか、遅刻しそうなのか、不安なのか、相手に会いたくないのかによって、身体の状態は変わります。</p>
<p>大切なのは、「この人物はこう歩く」と型を決めることではありません。<strong>人物の目的や状態から身体を変え、その結果として歩き方が変わっていく</strong>ことです。</p>
<div class="hk-exercise">
<h3>歩き方から人物をつくる</h3>
<ol>
<li>普通に舞台を横切る。</li>
<li>速度を変える。</li>
<li>歩幅を変える。</li>
<li>方向を変える。</li>
<li>身体の質を変える。</li>
<li>「誰かに会いに行く」など、目的を一つ設定する。</li>
<li>目的を持って舞台を横切る。</li>
<li>見る側は、どんな人物や状態に見えたか伝える。</li>
<li>演じた側は、自分の意図と見え方を比べる。</li>
</ol>
</div>
