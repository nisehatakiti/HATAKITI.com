<li>目的を持って舞台を横切る。</li>
<li>見る側は「どう見えたか」を伝える。</li>
<li>演じた側は「何を意図したか」を伝える。</li>
</ol>
<p><strong>ポイント：</strong>大きく変えることが目的ではありません。小さな歩き方の違いから、人物の状態や目的がどう見えるのかを感じてみましょう。</p>
