<section class="hk-section">
<div class="hk-section-head"><h2>1　演技は「感情を見せる」こと？</h2><p>悲しい人物だから泣く。怒っている人物だから大声を出す。それだけでは演技を説明しきれません。</p></div>
<p>舞台上では、感情そのものを観客に渡すことはできません。俳優が置かれた状況の中で何かを見て、何かを求め、相手に働きかけた結果として、感情や身体の変化が現れます。</p>
<div class="hk-theory-note"><strong>考えてみよう：</strong>「悲しい人」を演じるのと、「どうしても相手に分かってほしい人」を演じるのでは、同じ悲しさでも行動は変わる。</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>2　演技には「内側」と「外側」の入口がある</h2></div>
<div class="hk-theory-grid">
<article><h3>内側から</h3><p>想像、感覚、記憶、人物の心理、目的などから身体や声の変化を生み出す。</p></article>
<article><h3>外側から</h3><p>姿勢、歩き方、リズム、空間、身体の形、声の調子などを変えることで人物を発見する。</p></article>
<article><h3>関係から</h3><p>相手の存在や反応を受け取り、自分の行動を変化させる。</p></article>
</div>
<p class="hk-textbook-note">実際の演技では、これらが混ざります。「内側だけ」「外側だけ」と決めつける必要はありません。</p>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>3　俳優は「人物」そのものになるのか</h2></div>
<p>俳優は自分自身とは違う人物を演じます。しかし、舞台上で使う身体、声、経験、想像力は俳優自身のものです。</p>
<p>だから演技には、<strong>自分を使うこと</strong>と<strong>自分と役を区別すること</strong>の両方が必要になります。</p>
<div class="hk-nyakakichi">
<div class="hk-nyakakichi-image"><img src="<?php echo esc_url( content_url( 'plugins/hatakiti-core/assets/images/nyakakichi/nyakakichi-question.png' ) ); ?>" alt="にゃかきち"></div>
<div class="hk-nyakakichi-question"><p>自分じゃない人になるのに、自分の身体を使うって不思議だニャ。</p></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>4　俳優と相手役</h2><p>一人で完結する演技は、実際の舞台では少数です。</p></div>
<p>相手が何をしているか、どう見ているか、どんな距離にいるか。その変化によって、自分の行動も変わります。</p>
<p><strong>相手を見る → 受け取る → 反応する → 行動する</strong>という循環は、多くの演技訓練で重要なテーマになります。</p>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>5　俳優と観客</h2></div>
<p>演技は相手役との関係だけでなく、観客との関係の中でも成立します。客席にどう見えるか、どこまで情報を渡すか、空間全体をどう使うかも演技の一部です。</p>
<p>ただし「観客を笑わせる」「泣かせる」という結果だけを追うのではなく、人物の行動や作品の目的から考えることが重要です。</p>
</section>

