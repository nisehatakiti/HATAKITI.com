<div class="hk-theory-note"><strong>例えば：</strong>人物の目的が曖昧ならスタニスラフスキー。相手を受け取れないならマイズナー。身体が固いならルコック。感覚や想像力を深めたいならメソッド系の訓練を調べてみる。</div>
