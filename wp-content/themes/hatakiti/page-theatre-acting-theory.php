<section class="hk-section">
<div class="hk-section-head"><h2>7　同じ台詞を4通りで考える</h2></div>
<div class="hk-theory-scene"><p class="scene-line">A　「帰ってきてくれて、ありがとう。」</p>
<ul>
<li><strong>スタニスラフスキー：</strong>この人物は相手に何を求めている？</li>
<li><strong>メソッド：</strong>この瞬間を人物はどんな感覚として経験している？</li>
<li><strong>マイズナー：</strong>相手の存在や反応をどう受け取っている？</li>
<li><strong>ルコック：</strong>身体、距離、リズム、空間をどう使う？</li>
</ul></div>
<p>同じ台詞でも、考える入口が変われば、身体や声、相手との関係も変わります。</p>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>8　では、どれを使えばいい？</h2></div>
