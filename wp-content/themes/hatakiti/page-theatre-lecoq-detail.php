<section class="hk-section">
<div class="hk-section-head"><h2>2　身体は「感情の形」になる</h2></div>
<p>同じ人物でも、重心が前にあるのか後ろにあるのか、身体が開いているのか閉じているのかによって、舞台上で受ける印象は変わります。</p>
<div class="hk-lecoq-body-grid">
<div><strong>重い</strong><span>重心が低い・動きが遅い・身体を支える力が大きい</span></div>
<div><strong>軽い</strong><span>重心が高い・弾む・方向転換が速い</span></div>
<div><strong>閉じる</strong><span>身体を小さくする・視線を限定する・内側へ集める</span></div>
<div><strong>開く</strong><span>胸や腕を広げる・視線を遠くへ向ける・空間を大きく使う</span></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>3　空間との関係をつくる</h2></div>
<p>ルコックの身体表現では、身体だけを見ません。どこにいるのか、相手との距離はどれくらいか、どの方向へ進むのか、空間が狭いのか広いのかも演技の材料になります。</p>
<div class="hk-lecoq-space">
<div class="space-item"><strong>近い</strong><span>相手の存在が強く感じられる</span></div>
<div class="space-item"><strong>遠い</strong><span>関係や緊張が別の形で見えてくる</span></div>
<div class="space-item"><strong>広い</strong><span>身体の大きな動きや移動が使える</span></div>
<div class="space-item"><strong>狭い</strong><span>身体の制約そのものが表現になる</span></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>4　マイムから「物」をつくる</h2></div>
<p>目の前に本物の道具がなくても、身体の使い方を具体的にすると、観客に物の存在を伝えることができます。</p>
<p>たとえば箱なら、大きさ、重さ、持ち手の位置、表面の硬さ、床との摩擦まで想像します。物を見せるのではなく、<strong>物との関係を身体で見せる</strong>のです。</p>
<div class="hk-lecoq-mime">
<div><strong>箱を持つ</strong><span>重さ・大きさ・高さ・持ち上げる力を決める</span></div>
<div><strong>扉を開ける</strong><span>取っ手の位置・抵抗・扉の重さを身体で表す</span></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>5　中立な身体から始める</h2></div>
<p>訓練では、最初から人物らしい癖をつけるのではなく、身体をできるだけニュートラルに戻して、そこから動きの違いを探ることがあります。</p>
<p>「老人を演じよう」と顔を作るのではなく、重心、歩幅、速度、呼吸、関節の使い方などを変えることで、身体全体から人物像を発見していきます。</p>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>6　マスクが俳優を変える</h2></div>
<p>ルコックの教育では、マスクを使った訓練も重要な位置を占めます。顔の細かな表情を使いにくくすることで、俳優は身体全体や空間との関係に注意を向けるようになります。</p>
<p>マスクは単なる小道具ではなく、身体の使い方を発見するための条件として働きます。</p>
<div class="hk-lecoq-mask"><strong>顔で説明しない</strong><span>身体・方向・速度・姿勢・空間で伝える</span></div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>7　即興は「自由に好きなことをする」ことではない</h2></div>
<p>ルコックの即興では、何でも自由にやればよいというより、ある条件や制約を与え、その中で身体や関係の可能性を探します。</p>
<div class="hk-lecoq-improv">
<div><strong>条件</strong><span>重い・狭い・速い・静か・雨が降っている</span></div>
<div><strong>身体</strong><span>その条件なら、歩き方や呼吸はどう変わる？</span></div>
<div><strong>発見</strong><span>偶然生まれた動きを演劇の素材として残す</span></div>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>8　5分エチュード「重い箱」</h2></div>
<div class="hk-lecoq-exercise">
<ol>
<li>何もない場所に箱があると想像する。</li>
<li>とても軽い箱として持ち上げる。</li>
<li>次に、10kg、30kg、50kgと重さを変える。</li>
<li>重さが変わるたびに、足、膝、背中、腕、呼吸、速度がどう変わるか観察する。</li>
<li>最後に、同じ箱を相手に渡す。相手は受け取った重さに身体で反応する。</li>
</ol>
<p class="hk-textbook-note">大切なのは、重いふりをすることではなく、重さという条件が身体の使い方を本当に変えているかを探すことです。</p>
</div>
</section>

<section class="hk-section">
<div class="hk-section-head"><h2>9　同じ場面をルコックで考える</h2></div>
<div class="hk-lecoq-scene">
<p class="scene-line">AはBに帰ってほしくない。</p>
<p>台詞だけで気持ちを説明するのではなく、二人の距離、身体の向き、近づく・離れる動き、速度、空間の広さを使って場面をつくります。</p>
<p><strong>目的は同じでも、身体と空間を変えると、場面の意味は変わります。</strong></p>
</div>
</section>

