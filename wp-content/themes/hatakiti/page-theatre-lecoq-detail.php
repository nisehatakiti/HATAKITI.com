<section class="hk-section">
<div class="hk-section-head"><h2>1　ルコックは何を考えたのか</h2></div>
<p>ジャック・ルコックは、俳優の身体を「台詞を運ぶための器」だけとして扱わず、身体そのものを演劇をつくるための重要な材料として考えました。</p>
<p>そのため、まず頭の中で人物を決めてから身体を動かすのではなく、動いてみることで人物や場面を発見する訓練が多くあります。</p>
<div class="hk-lecoq-principle"><strong>考える → 動く</strong><span>だけではなく、<strong>動く → 感じる → 発見する</strong>という順番も大切にする。</span></div>
</section>

