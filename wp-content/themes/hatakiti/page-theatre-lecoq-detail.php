<p><strong>身体 → 空間 → 動き → 即興 → 発見</strong></p>
<p>ルコックの考え方では、演技を頭の中だけで完成させてから身体に移すのではなく、身体を動かし、空間と関わり、条件を試すことで、まだ知らない人物や場面を発見していきます。</p>
<p>スタニスラフスキー、マイズナー、メソッド演技とは違う入口から、俳優の表現を考えることができます。</p></div>
</section>

