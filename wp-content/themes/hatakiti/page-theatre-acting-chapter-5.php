<section class="hk-section">
<div class="hk-section-head">
<h2>実践エチュード</h2>
<p>姿勢だけを変えて、同じ台詞から違う人物を作ってみます。</p>
</div>
<div class="hk-exercise">
<h3>姿勢だけで人物を変える　10分</h3>
<ol>
<li>「どうしたの？」という短い台詞を用意する。</li>
<li>普通の姿勢で一度演じる。</li>
<li>身体を開いた姿勢で演じる。</li>
<li>身体を閉じた姿勢で演じる。</li>
<li>前へ向かう姿勢、後ろへ引く姿勢など、さらに2種類試す。</li>
<li>声や表情を大きく変えず、姿勢だけで人物の印象を変える。</li>
<li>最後に、自分がどの姿勢でどんな人物に見えたか振り返る。</li>
</ol>
<p><strong>ポイント：</strong>大きく動くことが目的ではありません。姿勢の小さな違いが、人物の状態や相手との関係をどう変えて見せるのかを感じてみましょう。</p>
</div>
